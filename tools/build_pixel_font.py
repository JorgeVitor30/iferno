# Acentos: desenho de 2 linhas, centralizado em cima da letra.
ACCENT = {
    "agudo": ["..#", ".#."],
    "crase": ["#..", ".#."],
    "circ": [".#.", "#.#"],
    "til": [".#.#", "#.#."],
}
COMPOSED = {
    "á": ("a", "agudo"), "à": ("a", "crase"), "â": ("a", "circ"), "ã": ("a", "til"),
    "é": ("e", "agudo"), "ê": ("e", "circ"), "í": ("i", "agudo"),
    "ó": ("o", "agudo"), "ô": ("o", "circ"), "õ": ("o", "til"), "ú": ("u", "agudo"),
    "Á": ("A", "agudo"), "À": ("A", "crase"), "Â": ("A", "circ"), "Ã": ("A", "til"),
    "É": ("E", "agudo"), "Ê": ("E", "circ"), "Í": ("I", "agudo"),
    "Ó": ("O", "agudo"), "Ô": ("O", "circ"), "Õ": ("O", "til"), "Ú": ("U", "agudo"),
}


def rows_of(ch: str) -> list[str]:
    return G[ch].split("|")


def glyph_bitmap(ch: str) -> list[str]:
    """Bitmap completo da célula (CELL_H linhas)."""
    if ch in COMPOSED:
        base, acc = COMPOSED[ch]
        body = rows_of(base)
        w = len(body[0])
        cell = ["." * w for _ in range(CELL_H)]
        for i, r in enumerate(body):
            cell[BODY_TOP + i] = r
        # minúscula: acento logo acima do corpo (linhas 2-3); maiúscula: linhas 0-1
        top = 2 if base.islower() else 0
        if base == "i":
            cell[BODY_TOP + 2] = ".#." if w == 3 else cell[BODY_TOP + 2]  # tira o pingo
            cell[BODY_TOP] = "." * w
        a = ACCENT[acc]
        aw = len(a[0])
        x0 = max(0, (w - aw) // 2)
        for j, ar in enumerate(a):
            row = list(cell[top + j])
            for k, c in enumerate(ar):
                if c == "#" and x0 + k < w:
                    row[x0 + k] = "#"
            cell[top + j] = "".join(row)
        return cell
    if ch in ("ç", "Ç"):
        base = "c" if ch == "ç" else "C"
        cell = glyph_bitmap(base)
        w = len(cell[0])
        mid = w // 2
        r9 = ["."] * w
        r9[mid] = "#"
        r10 = ["."] * w
        r10[max(0, mid - 1)] = "#"
        cell[9] = "".join(r9)
        cell[10] = "".join(r10)
        return cell
    body = rows_of(ch)
    w = len(body[0])
    cell = ["." * w for _ in range(CELL_H)]
    for i, r in enumerate(body):
        cell[BODY_TOP + i] = r
    return cell


def main() -> None:
    chars = list(G.keys()) + list(COMPOSED.keys()) + ["ç", "Ç"]
    bitmaps = {c: glyph_bitmap(c) for c in chars}
    total_w = sum(len(b[0]) + 1 for b in bitmaps.values())
    img = Image.new("RGBA", (total_w, CELL_H), (0, 0, 0, 0))
    meta = {"height": CELL_H, "ascent": BODY_TOP + 7, "glyphs": {}}
    x = 0
    for c, bm in bitmaps.items():
        w = len(bm[0])
        for yy, row in enumerate(bm):
            for xx, p in enumerate(row):
                if p == "#":
                    img.putpixel((x + xx, yy), (255, 255, 255, 255))
        meta["glyphs"][c] = [x, w]
        x += w + 1
    OUT.mkdir(parents=True, exist_ok=True)
    img.save(OUT / "pixel_font.png")
    (OUT / "pixel_font.json").write_text(json.dumps(meta, ensure_ascii=False), encoding="utf-8")
    print(f"{len(bitmaps)} glifos, atlas {img.width}x{img.height}")


if __name__ == "__main__":
    main()
